Entity::Entity(QGraphicsItem* parent)
    : QObject(), QGraphicsPixmapItem(parent)
{
}

void Entity::moveLeft(int step)
{
	setX(x() - step);
}

void Entity::moveRight(int step)
{
	setX(x() + step);
}

void Entity::moveDown(int step)
{
	setY(y() + step);
}

void Entity::moveUp(int step)
{
	setY(y() - step);
}

int Entity::centerX()
{
	return x() + boundingRect().width() / 2;
}

int Entity::centerY()
{
	return y() + boundingRect().height() / 2;
}

int Entity::gridX()
{
	if (centerX() > 0)
		return centerX() / GRID_SIZE; 
	else
		return centerX() / GRID_SIZE - 1;
}

int Entity::gridY()
{
	return centerY() / GRID_SIZE;
}

int Entity::gridUp()
{
	if (gridX() > 0 && gridX() < 27)
		return maze[gridY() - 1][gridX()];
	else
		return 1;
}

int Entity::gridDown()
{
	if (gridX() > 0 && gridX() < 27)
		return maze[gridY() + 1][gridX()];
	else
		return 1;
}

int Entity::gridLeft()
{
	if (gridX() > 0 && gridX() < 27)
		return maze[gridY()][gridX() - 1];
	else
		return 0;
}

int Entity::gridRight()
{
	if (gridX() > 0 && gridX() < 27)
		return maze[gridY()][gridX() + 1];
	else
		return 0;
}

void Entity::changeSide()
{
	if (x() + Px <= 0)
		setX(x() + Px + MAP_WIDTH);
	else if	(x() >= MAP_WIDTH)
		setX(x() - Px - MAP_WIDTH);
}

bool Entity::isInsideBox()
{
	if (gridX() > 0 && gridX() < 27) {
		if (maze[gridY()][gridX()] == BOX)
			return true;
		return false;			
		}
	else
		return false;
}

bool Entity::isInsideTunnel()
{
	if ((gridY() == 14 && gridX() <= 5) || (gridY() == 14 && gridX() >= 22))
		return true;
	else
		return false;
}
